class ProductItem:

    def __init__(
        self,
        url="",
        name="",
        brand="",
        price="",
        rating="",
        reviews="",
        image="",
        category="",
        product_size="",
        shades="",
        description="",
        ingredients="",
        how_to=""
    ):
        self.url = url
        self.name = name
        self.brand = brand
        self.price = price
        self.rating = rating
        self.reviews = reviews
        self.image = image
        self.category = category
        self.product_size = product_size
        self.shades = shades
        self.description = description
        self.ingredients = ingredients
        self.how_to = how_to